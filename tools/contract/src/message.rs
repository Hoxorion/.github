//! A commit message brought under the contract, read from standard input and written to
//! standard output (a history rewrite's message filter):
//!
//! * the subject follows Conventional Commits: one already in the form is kept; any other is
//!   given the type its opening verb means (`Add …` is a `feat`, `Never …` a `fix`, `Test …`
//!   a `test`), its first letter lowered unless it is a name (`SetWorldBounds`, `Hoxorion`);
//! * any attribution of the work to an AI tool is taken out;
//! * it ends with the given `Signed-off-by`, once.
//!
//! `--overrides <file>` gives subjects the opening verb misreads, whole: `old<TAB>new` per line.

use std::io::{Read, Write};

use crate::{Result, flag};

const TYPES: [&str; 11] = ["feat", "fix", "docs", "test", "refactor", "perf", "chore", "build", "ci", "style", "revert"];
/// Words that mean an AI tool in an attribution line.
const AI: [&str; 6] = ["claude", "anthropic", "openai", "codex", "chatgpt", "copilot"];

pub fn run(args: &[String]) -> Result<()> {
    let signoff = flag(args, "--signoff")?;
    let mut message = String::new();
    std::io::stdin().read_to_string(&mut message).map_err(|error| format!("reading the message: {error}"))?;
    // Subjects the opening verb misreads, given whole: `old<TAB>new`, one per line.
    if let Ok(path) = flag(args, "--overrides") {
        let table = std::fs::read_to_string(path).map_err(|error| format!("{path}: {error}"))?;
        let subject = message.lines().next().unwrap_or_default();
        if let Some(new) = table.lines().find_map(|line| line.split_once('\t').filter(|(old, _)| *old == subject).map(|(_, new)| new)) {
            // `@path` replaces the whole message, for one whose body no longer says what
            // the commit does.
            message = match new.strip_prefix('@') {
                Some(file) => std::fs::read_to_string(file).map_err(|error| format!("{file}: {error}"))?,
                None => message.replacen(subject, new, 1),
            };
        }
    }
    let fixed = fix(&message, signoff);
    std::io::stdout().write_all(fixed.as_bytes()).map_err(|error| format!("writing the message: {error}"))
}

pub fn fix(message: &str, signoff: &str) -> String {
    let mut lines: Vec<String> = message.lines().map(str::to_owned).collect();
    if let Some(subject) = lines.first_mut() {
        *subject = conventional(subject);
    }
    lines.retain(|line| !is_ai_attribution(line));
    let signoff_line = format!("Signed-off-by: {signoff}");
    lines.retain(|line| line.trim() != signoff_line);
    while lines.last().is_some_and(|line| line.trim().is_empty()) {
        lines.pop();
    }
    // The sign-off joins the trailer block when the message ends in one, and opens its own
    // otherwise.
    let ends_in_trailers = lines.len() > 1 && lines.last().is_some_and(|line| is_trailer(line));
    if !ends_in_trailers {
        lines.push(String::new());
    }
    lines.push(signoff_line);
    let mut out = lines.join("\n");
    out.push('\n');
    out
}

fn is_trailer(line: &str) -> bool {
    line.split_once(": ").is_some_and(|(key, _)| !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '-'))
}

fn is_ai_attribution(line: &str) -> bool {
    let lower = line.to_lowercase();
    let attribution = lower.starts_with("co-authored-by:") || lower.contains("generated with") || lower.contains("generated by");
    attribution && AI.iter().any(|tool| lower.contains(tool))
}

/// Whether `subject` is already `type(scope)!: description`.
fn is_conventional(subject: &str) -> bool {
    let Some((head, rest)) = subject.split_once(": ") else { return false };
    let head = head.strip_suffix('!').unwrap_or(head);
    let kind = head.split_once('(').map_or(head, |(kind, scope)| if scope.ends_with(')') { kind } else { "" });
    TYPES.contains(&kind) && !rest.trim().is_empty()
}

/// The type a subject's opening words mean.
fn kind_of(subject: &str) -> (&'static str, Option<&'static str>) {
    let first = subject.split_whitespace().next().unwrap_or_default();
    let starts = |prefix: &str| subject.starts_with(prefix);
    if starts("Initial commit") {
        return ("chore", None);
    }
    if starts("Test map") || starts("Test in the game") || starts("Start the test map") {
        return ("feat", Some("test-map"));
    }
    if first == "Test" {
        return ("test", None);
    }
    if starts("Update ") && subject.contains("security") {
        return ("build", Some("deps"));
    }
    if starts("Build as ") {
        return ("build", None);
    }
    match first {
        "Document" | "Describe" | "Explain" | "Say" | "Escalator" => ("docs", None),
        "Never" | "Do" | "Stop" | "Refuse" | "Ignore" | "Rebase" | "Report" | "Pads" | "On-foot" | "Car" | "Close" => ("fix", None),
        "Remove" | "Rename" | "Replace" | "Fold" | "Name" | "Use" | "Make" if subject.contains(" instead") || first != "Make" => ("refactor", None),
        _ => ("feat", None),
    }
}

/// `subject` in Conventional Commits form.
pub fn conventional(subject: &str) -> String {
    if is_conventional(subject) {
        return subject.to_owned();
    }
    let (kind, scope) = kind_of(subject);
    // "Test map: X" and the like carry their own topic, which becomes the scope.
    let text = match scope {
        Some(_) => subject.split_once(": ").map_or(subject, |(_, rest)| rest),
        None => subject,
    };
    let text = if text == "Initial commit" { "initial commit".to_owned() } else { lower_first(text) };
    match scope {
        Some(scope) => format!("{kind}({scope}): {text}"),
        None => format!("{kind}: {text}"),
    }
}

/// Lowers the first letter of an ordinary word; a name (`SetWorldBounds`, `ServerEvent::…`,
/// `Hoxorion`) keeps its case.
fn lower_first(text: &str) -> String {
    let word = text.split_whitespace().next().unwrap_or_default();
    let tail = word.chars().skip(1);
    let is_name = tail.clone().any(|c| c.is_uppercase()) || word.contains("::") || ["Hoxorion", "Snap", "Wine", "Windows", "Linux", "MSIX", "README"].contains(&word);
    if is_name {
        return text.to_owned();
    }
    let mut chars = text.chars();
    chars.next().map_or_else(String::new, |first| first.to_lowercase().chain(chars).collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    const ME: &str = "NullSablex <me@example.org>";

    #[test]
    fn a_conventional_subject_is_kept() {
        for subject in ["feat(net): carry a shot", "fix!: x", "chore(license): y", "build(deps): z"] {
            assert_eq!(conventional(subject), subject);
        }
    }

    #[test]
    fn other_subjects_get_their_type() {
        assert_eq!(conventional("Initial commit"), "chore: initial commit");
        assert_eq!(conventional("Add the Snap package"), "feat: add the Snap package");
        assert_eq!(conventional("Never seat a ped in a seat it lacks"), "fix: never seat a ped in a seat it lacks");
        assert_eq!(conventional("Test that a shot arrives"), "test: test that a shot arrives");
        assert_eq!(conventional("Test map: no distant gunfire"), "feat(test-map): no distant gunfire");
        assert_eq!(conventional("Document the player color"), "docs: document the player color");
        assert_eq!(conventional("SetWorldBounds confines players for real"), "feat: SetWorldBounds confines players for real");
        assert_eq!(conventional("ServerEvent::PedAnimation and PedInvulnerable"), "feat: ServerEvent::PedAnimation and PedInvulnerable");
        assert_eq!(conventional("Hoxorion Map Editor: a native map editor"), "feat: Hoxorion Map Editor: a native map editor");
        assert_eq!(conventional("Update certifi and tokio for their security fixes"), "build(deps): update certifi and tokio for their security fixes");
    }

    #[test]
    fn ai_attribution_goes_and_the_signoff_is_there_once() {
        let message = "feat: x\n\nBody.\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\nSigned-off-by: NullSablex <me@example.org>\n";
        let fixed = fix(message, ME);
        assert_eq!(fixed, "feat: x\n\nBody.\n\nSigned-off-by: NullSablex <me@example.org>\n");
        assert_eq!(fix(&fixed, ME), fixed, "running again changes nothing");
        assert_eq!(fix("Initial commit\n", ME), "chore: initial commit\n\nSigned-off-by: NullSablex <me@example.org>\n");
        let human = "feat: x\n\nCo-authored-by: Someone <s@example.org>\n";
        assert!(fix(human, ME).contains("Co-authored-by: Someone"), "a person stays");
    }
}
